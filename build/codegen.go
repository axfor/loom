package build

// Compiling a template to Go.
//
// What is compiled is the control flow: an if becomes an if, a caught result becomes a variable
// the generated code tests, a return becomes a return. What the statements do is not compiled —
// each one is a value handed to the runtime, which knows how to place it. That split is the whole
// design: the part that decides is native code, the part that edits documents is a library both
// the compiler and the compiled program share, so a weaver cannot drift from lm build.

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/axfor/loom/lang"
)

// Generate writes the Go source of a weaver for one template.
func Generate(c *lang.Config, t *lang.Template, pkg string) ([]byte, error) {
	g := &gen{t: t}
	g.line("// Code generated by lm compile. DO NOT EDIT.")
	g.line("//")
	g.line("// Woven from %s onto %s.", lang.Rel(c, t.Path), t.BasePath)
	g.line("package %s", pkg)
	g.line("")
	g.line("import (")
	g.line("\t%q", "github.com/axfor/loom/lang")
	g.line("\t%q", "github.com/axfor/loom/loomrt")
	g.line(")")
	g.line("")
	g.meta(c, t)
	g.line("")
	g.line("func weave(w *loomrt.Weaver) error {")
	if err := g.body(t.Stmts, 1); err != nil {
		return nil, err
	}
	g.line("\treturn nil")
	g.line("}")
	g.line("")
	g.line("func main() { loomrt.Main(meta, weave) }")
	src := []byte(g.b.String())
	out, err := format.Source(src)
	if err != nil {
		return src, fmt.Errorf("the generated program does not parse — this is a bug in lm compile: %v", err)
	}
	return out, nil
}

type gen struct {
	b strings.Builder
	t *lang.Template
	n int
}

func (g *gen) line(f string, a ...any) {
	fmt.Fprintf(&g.b, f, a...)
	g.b.WriteByte('\n')
}

func (g *gen) meta(c *lang.Config, t *lang.Template) {
	marks := map[string]lang.Marks{}
	if l, ok := c.Layer(c.Weft); ok {
		for k, v := range l.Marks {
			marks[k] = v
		}
	}
	g.line("var meta = loomrt.Meta{")
	g.line("\tTarget: %q, Type: %q, BasePath: %q,", t.Target, t.Type, t.BasePath)
	if t.From != "" {
		g.line("\tFrom: %q, Source: %q, UseReason: %q,", t.From, t.Source, t.UseReason)
	}
	g.line("\tLoom: %q, Frontmatter: %q, Keys: %q, Body: %q,", c.Loom, c.Frontmatter, c.Keys, c.Body)
	if len(marks) > 0 {
		g.line("\tMarks: map[string]lang.Marks{")
		var kinds []string
		for k := range marks {
			kinds = append(kinds, k)
		}
		sort.Strings(kinds)
		for _, k := range kinds {
			g.line("\t\t%q: {Begin: %q, End: %q},", k, marks[k].Begin, marks[k].End)
		}
		g.line("\t},")
	}
	if len(t.Resources) > 0 {
		g.line("\tResources: []lang.Resource{")
		for _, r := range t.Resources {
			g.line("\t\t{Name: %q, Docs: []lang.ResourceDoc{", r.Name)
			for _, d := range r.Docs {
				g.line("\t\t\t{Kind: %q, Text: %s},", d.Kind, strconv.Quote(d.Text))
			}
			g.line("\t\t}},")
		}
		g.line("\t},")
	}
	g.line("}")
}

// body writes one run of statements. An if is an if; everything else is a value the runtime places.
func (g *gen) body(ss []lang.Stmt, depth int) error {
	tab := strings.Repeat("\t", depth)
	for _, s := range ss {
		switch s.Op {
		case "if":
			cond, err := g.cond(s.Cond)
			if err != nil {
				return err
			}
			g.line("%sif %s {", tab, cond)
			if err := g.body(s.Kids, depth+1); err != nil {
				return err
			}
			if len(s.Else) > 0 {
				g.line("%s} else {", tab)
				if err := g.body(s.Else, depth+1); err != nil {
					return err
				}
			}
			g.line("%s}", tab)
		case "stop":
			g.line("%sw.Stop()", tab)
			g.line("%sreturn nil", tab)
		case "fail":
			args := make([]string, 0, len(s.Errf))
			for _, r := range s.Errf[1:] {
				if r.IsLit {
					args = append(args, strconv.Quote(r.Literal))
					continue
				}
				args = append(args, fmt.Sprintf("w.Why(%q)", r.Anchor))
			}
			g.line("%sreturn w.Fail(fmt.Sprintf(%s%s))", tab, strconv.Quote(s.Errf[0].Literal), joinPrefixed(args))
		default:
			name := fmt.Sprintf("s%d", g.n)
			g.n++
			g.line("%s%s := %s", tab, name, stmtLit(s))
			if s.Assign != "" {
				g.line("%sw.Try(%q, %s)", tab, s.Assign, name)
				continue
			}
			g.line("%sw.Do(%s)", tab, name)
		}
	}
	return nil
}

func joinPrefixed(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return ", " + strings.Join(args, ", ")
}

func (g *gen) cond(c *lang.Cond) (string, error) {
	var q string
	switch {
	case c.Var != "":
		q = fmt.Sprintf("w.Held(%q)", c.Var)
	case c.Has != "":
		q = fmt.Sprintf("w.Has(%q, %q)", c.Kind, c.Has)
	case c.Any:
		q = fmt.Sprintf("w.Any(%s)", selLit(c.Sel))
	default:
		return "", fmt.Errorf("%s: this condition asks nothing", c.Rng)
	}
	if c.Not {
		return "!" + q, nil
	}
	return q, nil
}

// stmtLit writes a statement as the Go value the runtime will place. Only the fields an operation
// reads are written, so the generated source says what the statement is rather than what a struct
// happens to have.
func stmtLit(s lang.Stmt) string {
	var f []string
	add := func(k, v string) { f = append(f, k+": "+v) }
	add("Op", strconv.Quote(s.Op))
	if s.Kind != "" {
		add("Kind", strconv.Quote(s.Kind))
	}
	if s.Anchor != "" {
		add("Anchor", strconv.Quote(s.Anchor))
	}
	if s.Ident {
		add("Ident", "true")
	}
	if len(s.Within) > 0 {
		var segs []string
		for _, w := range s.Within {
			segs = append(segs, fmt.Sprintf("{Name: %q, Ident: %v}", w.Name, w.Ident))
		}
		add("Within", "[]lang.Seg{"+strings.Join(segs, ", ")+"}")
	}
	if s.Axis != "" {
		add("Axis", strconv.Quote(s.Axis))
	}
	if s.Select != nil {
		add("Select", selLit(s.Select))
	}
	if len(s.Srcs) > 0 {
		var rs []string
		for _, r := range s.Srcs {
			rs = append(rs, refLit(r))
		}
		add("Srcs", "[]lang.Ref{"+strings.Join(rs, ", ")+"}")
	}
	if s.As != "" {
		add("As", strconv.Quote(s.As))
	}
	if s.Key != "" {
		add("Key", strconv.Quote(s.Key))
	}
	if len(s.Kids) > 0 {
		var ks []string
		for _, k := range s.Kids {
			ks = append(ks, stmtLit(k))
		}
		add("Kids", "[]lang.Stmt{"+strings.Join(ks, ", ")+"}")
	}
	if s.Layer != "" {
		add("Layer", strconv.Quote(s.Layer))
	}
	if s.File != "" {
		add("File", strconv.Quote(s.File))
	}
	if s.SetKey != "" {
		add("SetKey", strconv.Quote(s.SetKey))
	}
	if s.Op == "value" {
		add("SetRef", refLit(s.SetRef))
	}
	if s.Mode != "" {
		add("Mode", strconv.Quote(s.Mode))
	}
	if s.Reason != "" {
		add("Reason", strconv.Quote(s.Reason))
	}
	if s.Move != nil {
		add("Move", fmt.Sprintf("&lang.Move{Side: %q, Kind: %q, Anchor: %q, Ident: %v}", s.Move.Side, s.Move.Kind, s.Move.Anchor, s.Move.Ident))
	}
	// The position is what an error points at, so it is carried into the binary too.
	add("Rng", fmt.Sprintf("lang.Pos{File: %q, Line: %d, Col: %d}", s.Rng.File, s.Rng.Line, s.Rng.Col))
	return "lang.Stmt{" + strings.Join(f, ", ") + "}"
}

func refLit(r lang.Ref) string {
	var f []string
	add := func(k, v string) { f = append(f, k+": "+v) }
	if r.Layer != "" {
		add("Layer", strconv.Quote(r.Layer))
	}
	if r.Kind != "" {
		add("Kind", strconv.Quote(r.Kind))
	}
	if r.Anchor != "" {
		add("Anchor", strconv.Quote(r.Anchor))
	}
	if r.IsLit {
		add("IsLit", "true")
		add("Literal", strconv.Quote(r.Literal))
	}
	if r.File != "" {
		add("File", strconv.Quote(r.File))
	}
	if r.Ident {
		add("Ident", "true")
	}
	if r.Res != "" {
		add("Res", strconv.Quote(r.Res))
	}
	if r.ResKind != "" {
		add("ResKind", strconv.Quote(r.ResKind))
	}
	if len(r.Within) > 0 {
		var segs []string
		for _, w := range r.Within {
			segs = append(segs, fmt.Sprintf("{Name: %q, Ident: %v}", w.Name, w.Ident))
		}
		add("Within", "[]lang.Seg{"+strings.Join(segs, ", ")+"}")
	}
	if r.Project != nil {
		add("Project", selLit(r.Project))
	}
	return "lang.Ref{" + strings.Join(f, ", ") + "}"
}

func selLit(s *lang.Select) string {
	if s == nil {
		return "nil"
	}
	var f []string
	f = append(f, fmt.Sprintf("Kind: %q", s.Kind))
	if s.Match != "" {
		f = append(f, fmt.Sprintf("Match: %q", s.Match))
	}
	if s.Level != 0 {
		f = append(f, fmt.Sprintf("Level: %d", s.Level))
	}
	if s.Empty {
		f = append(f, "Empty: true")
	}
	if s.Pred != nil {
		f = append(f, "Pred: "+predLit(s.Pred))
	}
	return "&lang.Select{" + strings.Join(f, ", ") + "}"
}

func predLit(p *lang.Pred) string {
	var f []string
	if p.Op != "" {
		f = append(f, fmt.Sprintf("Op: %q", p.Op))
		var ks []string
		for i := range p.Kids {
			ks = append(ks, strings.TrimPrefix(predLit(&p.Kids[i]), "&lang.Pred"))
		}
		f = append(f, "Kids: []lang.Pred{lang.Pred"+strings.Join(ks, ", lang.Pred")+"}")
	}
	if p.Field != "" {
		f = append(f, fmt.Sprintf("Field: %q", p.Field))
	}
	if p.Cmp != "" {
		f = append(f, fmt.Sprintf("Cmp: %q", p.Cmp))
	}
	if p.Str != "" {
		f = append(f, fmt.Sprintf("Str: %q", p.Str))
	}
	if p.Num != 0 {
		f = append(f, fmt.Sprintf("Num: %d", p.Num))
	}
	return "&lang.Pred{" + strings.Join(f, ", ") + "}"
}
